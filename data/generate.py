"""Generate the synthetic OTP-scam dataset: train, held-out test, and a shifted (drift) set.

Usage:
    python data/generate.py --out data/processed --seed 42
    python data/check_dataset.py --data data/processed          # prove the dataset is sound

All data is synthetic and generated by this script. No third-party dataset is used.

Design decisions (each one is explained in DATA_CARD.md):
 1. Two labels (scam / safe) plus a subtype, so errors can be read per kind of message.
 2. Safe messages are mostly HARD negatives: genuine bank OTPs, alerts and warnings. A scam
    detector that only learns "mentions a bank or a code = scam" fails on these.
 3. Messages are assembled from parts (pretext + request + urgency + closing). Urgency, closings,
    codes, links, phone numbers and "don't share" wording appear in BOTH classes, so no single
    surface cue gives the label away.
 4. Every language is roughly balanced between scam and safe, so the script a message is written
    in never predicts the label.
 5. Test uses phrasings never seen in training (every 4th template is held out), so the score
    measures generalisation to new wording, not memorisation.
 6. A template_id column lets training use GroupKFold, so cross-validation is honest too.
 7. The shifted set has new senders, new pretexts and more Tanglish, half scam and half genuine.
    It is split by phrasing into shifted_review (what human reviewers would label) and
    shifted_eval (never trained on), so retraining gains are measured honestly.
 8. All bank and wallet names are fictional, phone numbers are masked, links use the reserved
    .example domain, codes are random. No real personal data (PDPA No. 9 of 2022).
"""
