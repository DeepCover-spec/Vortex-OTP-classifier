def noise(r, s, lang):
    """Light realism: casing, dropped punctuation, doubled spaces, occasional emoji, latin typos."""
    if lang in ("en", "singlish", "tanglish"):
        if r.random() < 0.12: s = s.lower()
        if r.random() < 0.06: s = s.upper()
        if r.random() < 0.15: s = s.replace(".", "", 1)
        if r.random() < 0.1:
            words = s.split(" ")
            i = r.randrange(len(words))
            w = words[i]
            if len(w) > 4: words[i] = w[:2] + w[3:]          # drop a letter
            s = " ".join(words)
    if r.random() < 0.08: s = s.replace(" ", "  ", 1)
    if r.random() < 0.06: s += r.choice([" 🙏", " ⚠️", " !!", " ..."])
    return re.sub(r"\s+$", "", s)


